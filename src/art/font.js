// Acentos desenhados acima (2 fileiras) ou cedilha abaixo.
const MARKS = {
  acute: ['001', '010'], grave: ['100', '010'], circ: ['010', '101'], tilde: ['011', '110'],
};
const ACCENTED = {
  Á: ['A', 'acute'], À: ['A', 'grave'], Â: ['A', 'circ'], Ã: ['A', 'tilde'],
  É: ['E', 'acute'], Ê: ['E', 'circ'], Í: ['I', 'acute'], Ó: ['O', 'acute'],
  Ô: ['O', 'circ'], Õ: ['O', 'tilde'], Ú: ['U', 'acute'], Ç: ['C', 'cedilla'],
};

export const LINE_HEIGHT = 9; // 3 acima para acentos + 5 + 1 abaixo para cedilha

function glyphFor(ch) {
  const up = ch.toUpperCase();
  if (ACCENTED[up]) return { base: G[ACCENTED[up][0]], mark: ACCENTED[up][1] };
  return { base: G[up] ?? G['?'], mark: null };
}

export function measure(text, scale = 1) {
  let w = 0;
  for (const ch of text) w += (glyphFor(ch).base[0].length + 1) * scale;
  return Math.max(0, w - scale);
}

/**
 * Escreve texto. (x, y) é o topo das letras maiúsculas (acentos sobem até 3 px acima).
 * opts: color, scale, shadow (cor do contorno/sombra), align ('left'|'center'|'right'), outline (bool)
 */
export function text(ctx, str, x, y, opts = {}) {
  const { color = '#ffffff', scale = 1, shadow = null, align = 'left', outline = false } = opts;
  const w = measure(str, scale);
  let cx = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? x - w : x;
  const plot = (px, py, c) => { ctx.fillStyle = c; ctx.fillRect(px, py, scale, scale); };
  const drawGlyph = (g, gx, gy, c) => {
    g.base.forEach((row, j) => [...row].forEach((b, i) => b === '1' && plot(gx + i * scale, gy + j * scale, c)));
    if (g.mark === 'cedilla') plot(gx + 1 * scale, gy + 5 * scale, c);
    else if (g.mark) MARKS[g.mark].forEach((row, j) => [...row].forEach((b, i) => b === '1' && plot(gx + i * scale, gy + (j - 3) * scale, c)));
  };
  for (const ch of str) {
    const g = glyphFor(ch);
    if (shadow) {
      if (outline) {
        for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) drawGlyph(g, cx + ox * scale, y + oy * scale, shadow);
      } else {
        drawGlyph(g, cx + scale, y + scale, shadow);
      }
    }
    drawGlyph(g, cx, y, color);
    cx += (g.base[0].length + 1) * scale;
  }
  return w;
}
